// Geocoding cache entry interface
interface GeocodingCacheEntry {
  lon: number;
  lat: number;
  timestamp: number;
  provider: string;
  qualifier?: string;
  score?: number;
  normalizedAddress?: string;
  addressComponents?: GoogleAddressComponents;
  geocodeMethod?: OdaGeocodeMetadata['geocodeMethod'];
  confidence?: number;
  distanceMeters?: number;
  matchedFields?: string[];
  mailingAddress?: OdaGeocodeMetadata['mailingAddress'];
  dataSource?: OdaGeocodeMetadata['dataSource'];
}

// Reverse geocoding cache entry interface
