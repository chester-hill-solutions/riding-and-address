#!/usr/bin/env node
/**
 * Import-cycle gate.
 *
 * **Only runtime edges count.** A `import type { X } from './y'` is erased at compile time, so it
 * cannot close a loop at runtime — it closes a loop in the *type* graph, which TypeScript handles
 * and which has never once caused a bug. Counting type-only edges as cycles produces a gate that
 * cries wolf, and a gate that cries wolf is a gate nobody reads.
 *
 * So this counts value imports and value re-exports, and nothing else. The count it maintains is
 * the one that matters: how many groups of modules import each other in a circle.
 *
 * **A ratchet, not a cliff.** The baseline is a tracked file, so the diff in the pull request that
 * changes it is the review surface: a cycle that appears is a visible decision, not a silent one.
 *
 *   node scripts/check-import-cycles.mjs           # check
 *   node scripts/check-import-cycles.mjs --update  # rewrite the baseline from this run
 *
 * Wired into `npm run validate` and CI.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const BASELINE_PATH = path.join(ROOT, 'test', 'import-cycle-baseline.json');

const UPDATE = process.argv.includes('--update');

/**
 * The value-import graph.
 *
 * `import { a, type B } from './x'` has one value binding and one type binding, so it is a value
 * edge. `import type { A } from './x'` is not. `export { a } from './x'` is — a re-export is a
 * runtime binding, and it is exactly how the cycle this gate exists to catch was sustained for
 * months: a backward-compatibility re-export with no importers.
 */
function buildGraph() {
  const files = existsSync(SRC)
    ? execFileSync('ls', ['-1', SRC], { encoding: 'utf8' })
        .split('\n')
        .filter((name) => name.endsWith('.ts'))
    : [];

  const graph = {};
  for (const file of files) {
    const source = readFileSync(path.join(SRC, file), 'utf8');
    const edges = new Set();
    const pattern = /(?:^|\n)\s*(import|export)\s+(type\s+)?([\s\S]*?)from\s+'\.\/([a-z0-9-]+)'/g;
    let match;
    while ((match = pattern.exec(source)) !== null) {
      const isTypeOnly = Boolean(match[2]);
      const clause = match[3];
      const inner = clause.replace(/[{}]/g, '').trim();

      let hasValue = false;
      if (!isTypeOnly) {
        for (const part of inner.split(',')) {
          const binding = part.trim();
          if (!binding) continue;
          if (/^type\s/.test(binding)) continue;
          hasValue = true;
        }
        // A default import is a value binding.
        if (/^[A-Za-z_$][\w$]*\s*(,|$)/.test(inner)) hasValue = true;
      }

      const target = `${match[4]}.ts`;
      if (hasValue && existsSync(path.join(SRC, target))) edges.add(target);
    }
    graph[file] = [...edges];
  }
  return { graph, files };
}

/** Tarjan's algorithm: the strongly-connected components with more than one member are the cycles. */
function cyclicComponents(graph, files) {
  let index = 0;
  const stack = [];
  const onStack = new Set();
  const indices = {};
  const lowLink = {};
  const components = [];

  const strongConnect = (node) => {
    indices[node] = index;
    lowLink[node] = index;
    index += 1;
    stack.push(node);
    onStack.add(node);

    for (const next of graph[node] ?? []) {
      if (indices[next] === undefined) {
        strongConnect(next);
        lowLink[node] = Math.min(lowLink[node], lowLink[next]);
      } else if (onStack.has(next)) {
        lowLink[node] = Math.min(lowLink[node], indices[next]);
      }
    }

    if (lowLink[node] === indices[node]) {
      const component = [];
      let member;
      do {
        member = stack.pop();
        onStack.delete(member);
        component.push(member);
      } while (member !== node);
      if (component.length > 1) components.push(component.sort());
    }
  };

  for (const file of files) {
    if (indices[file] === undefined) strongConnect(file);
  }
  return components.sort((a, b) => a[0].localeCompare(b[0]));
}

const { graph, files } = buildGraph();
const cycles = cyclicComponents(graph, files);

if (UPDATE) {
  const baseline = {
    _comment:
      'The number of runtime import cycles in src/. Generated by ' +
      '`node scripts/check-import-cycles.mjs --update`. Type-only imports do not count — they are ' +
      'erased at compile time and cannot close a runtime loop. The gate fails when the count goes ' +
      'UP, so a cycle that appears is a visible decision rather than a silent one.',
    cycles: cycles.length,
    groups: cycles,
  };
  writeFileSync(BASELINE_PATH, `${JSON.stringify(baseline, null, 2)}\n`);
  console.log(`import-cycles: baseline written (${cycles.length} cyclic group(s))`);
  process.exit(0);
}

if (!existsSync(BASELINE_PATH)) {
  console.error(
    'import-cycles: no baseline. Run `node scripts/check-import-cycles.mjs --update` to create one.'
  );
  process.exit(1);
}

const baseline = JSON.parse(readFileSync(BASELINE_PATH, 'utf8'));
const allowed = baseline.cycles ?? 0;

if (cycles.length > allowed) {
  console.error(`import-cycles: ${cycles.length} cyclic group(s); the baseline allows ${allowed}\n`);
  for (const component of cycles) {
    console.error(`  ${component.join(' -> ')}`);
  }
  console.error(
    '\nA new cycle is a new coupling. If it is deliberate, run ' +
      '`node scripts/check-import-cycles.mjs --update` and say why in the commit.'
  );
  process.exit(1);
}

console.log(
  `import-cycles: ok (${cycles.length} cyclic group(s), baseline allows ${allowed}; ` +
    `${files.length} modules scanned)`
);
