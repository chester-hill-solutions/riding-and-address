#!/usr/bin/env node
/**
 * Coverage ratchet.
 *
 * **A ratchet, not a cliff.** An absolute coverage threshold fails the build on day one and then
 * teaches the team to ignore the gate. A ratchet fails only on *regression* — a file whose
 * coverage went down relative to the committed baseline — which is the property that actually
 * matters and the only one a team keeps.
 *
 * The baseline is a tracked file, so the diff in the pull request that changes it is the review
 * surface: a floor that went down is a visible decision, not a silent one.
 *
 *   node scripts/check-coverage-ratchet.mjs           # check
 *   node scripts/check-coverage-ratchet.mjs --update  # rewrite the baselines from this run
 *
 * Wired into `npm run validate` and CI. The repository's existing ratchet — see
 * docs/reviews/2026-07-16-strictness-ratchet.md — is the same idea applied to rules; this is the
 * same idea applied to coverage.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const UPDATE = process.argv.includes('--update');

/**
 * The two packages that are measured.
 *
 * The portal is a separate package with its own vitest config and its own node_modules, so it is
 * a separate run — but it is the *paid* half of the product, and its coverage was three files and
 * eight tests. Leaving it out of the ratchet would leave the most under-tested surface out of the
 * gate that is supposed to stop coverage falling.
 */
const TARGETS = [
  {
    name: 'root',
    cwd: ROOT,
    include: 'src/**',
    baseline: path.join(ROOT, 'test', 'coverage-baseline.json'),
    coverageDir: path.join(ROOT, 'node_modules', '.cache', 'coverage-ratchet'),
    prefix: 'src/',
  },
  {
    name: 'portal',
    cwd: path.join(ROOT, 'portal'),
    include: 'app/**/*.{ts,tsx}',
    baseline: path.join(ROOT, 'portal', 'test', 'coverage-baseline.json'),
    coverageDir: path.join(ROOT, 'node_modules', '.cache', 'coverage-ratchet-portal'),
    prefix: 'portal/app/',
  },
];

/** The metrics a floor is recorded for. Line coverage is left out: it tracks statements closely
 * enough that recording it too would only add noise to the baseline. */
const METRICS = ['statements', 'branches'];

function runCoverage(target) {
  mkdirSync(target.coverageDir, { recursive: true });
  execFileSync(
    'bunx',
    [
      'vitest', 'run',
      '--coverage',
      '--coverage.provider=v8',
      `--coverage.include=${target.include}`,
      '--coverage.reporter=json-summary',
      `--coverage.reportsDirectory=${target.coverageDir}`,
    ],
    { cwd: target.cwd, stdio: 'inherit' }
  );
  const summaryPath = path.join(target.coverageDir, 'coverage-summary.json');
  if (!existsSync(summaryPath)) {
    throw new Error(`coverage summary was not written to ${summaryPath}`);
  }
  return JSON.parse(readFileSync(summaryPath, 'utf8'));
}

/** Per-file floors, keyed by repository-relative path. */
function floorsFrom(summary, target) {
  const files = {};
  for (const [key, value] of Object.entries(summary)) {
    if (key === 'total') continue;
    // The summary keys are absolute paths. Each target knows its own source root, so the path is
    // cut at that marker and re-prefixed with the repository-relative form.
    const marker = target.prefix === 'src/' ? '/src/' : '/portal/app/';
    const at = key.indexOf(marker);
    const relative = at >= 0 ? key.slice(at + marker.length) : path.basename(key);
    files[`${target.prefix}${relative}`] = {
      statements: value.statements.pct,
      branches: value.branches.pct,
    };
  }
  return files;
}

const violations = [];
const stale = [];
const summaries = [];

for (const target of TARGETS) {
  const summary = runCoverage(target);
  summaries.push({ target, summary });
  const current = floorsFrom(summary, target);

  if (UPDATE) {
    const baseline = {
      _comment:
        `Coverage floors per file for the ${target.name} package. Generated by ` +
        '`node scripts/check-coverage-ratchet.mjs --update`. The gate fails when a file falls below ' +
        'its floor, so this file only ever needs to change when coverage moves — and the diff is ' +
        'the review surface. A floor that goes DOWN is a decision somebody made on purpose, and it ' +
        'is visible here.',
      files: current,
    };
    mkdirSync(path.dirname(target.baseline), { recursive: true });
    writeFileSync(target.baseline, `${JSON.stringify(baseline, null, 2)}\n`);
    console.log(
      `coverage-ratchet: ${target.name} baseline written (${Object.keys(current).length} files)`
    );
    continue;
  }

  if (!existsSync(target.baseline)) {
    console.error(
      `coverage-ratchet: no ${target.name} baseline. Run ` +
        '`node scripts/check-coverage-ratchet.mjs --update` to create one.'
    );
    process.exit(1);
  }

  const baseline = JSON.parse(readFileSync(target.baseline, 'utf8'));
  for (const [file, floors] of Object.entries(baseline.files ?? {})) {
    const actual = current[file];
    if (!actual) {
      // The file is gone. That is not a coverage regression, but the baseline is now describing a
      // file that does not exist, and it should be updated rather than left to rot.
      stale.push({ target: target.name, file });
      continue;
    }
    for (const metric of METRICS) {
      const floor = floors[metric];
      if (typeof floor !== 'number') continue;
      const got = actual[metric];
      // A one-point drop is noise from a changed test order; a real regression is larger. The
      // tolerance keeps the gate honest rather than twitchy.
      if (got < floor - 1) {
        violations.push({ target: target.name, file, metric, floor, got });
      }
    }
  }
}

if (UPDATE) {
  process.exit(0);
}

if (violations.length || stale.length) {
  if (violations.length) {
    console.error(`coverage-ratchet: ${violations.length} coverage regression(s)\n`);
    for (const v of violations) {
      console.error(
        `  [${v.target}] ${v.file} — ${v.metric} fell to ${v.got}% from a floor of ${v.floor}%`
      );
    }
  }
  if (stale.length) {
    console.error(`\ncoverage-ratchet: ${stale.length} baseline entr(ies) for files that no longer exist\n`);
    for (const { target, file } of stale) {
      console.error(`  [${target}] ${file} — removed or renamed; run with --update to drop the entry`);
    }
  }
  console.error(
    '\nCoverage went down. Either restore the tests, or — if the drop is deliberate — run ' +
      '`node scripts/check-coverage-ratchet.mjs --update` and explain the change in the commit.'
  );
  process.exit(1);
}

const totals = summaries
  .map(({ target, summary }) => `${target.name} ${summary.total.statements.pct}%/${summary.total.branches.pct}%`)
  .join(', ');
console.log(`coverage-ratchet: ok (${totals})`);
